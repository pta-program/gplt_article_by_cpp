#include <iostream>
using namespace std;

/**
 * L1-001 - Hello World
 * 
 * 实现原理：
 * 这是一个最简单的程序，不需要任何输入处理。
 * 直接使用 cout 输出字符串 "Hello World!" 到标准输出即可。
 * 
 * 解题思路：
 * 1. 包含必要的头文件 <iostream>，用于输入输出操作
 * 2. 使用 namespace std 简化代码，避免每次都写 std::
 * 3. 在 main 函数中直接输出指定字符串
 */
int main() {
    cout << "Hello World!" << endl;
    return 0;
}