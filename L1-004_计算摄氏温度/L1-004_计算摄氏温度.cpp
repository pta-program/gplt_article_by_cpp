#include <iostream>
using namespace std;

/**
 * L1-004 - 计算摄氏温度
 * 
 * 实现原理：
 * 根据题目给出的公式进行温度转换：C = 5 * (F - 32) / 9
 * 由于输入输出都是整数，直接使用整数运算即可。
 * 
 * 解题思路：
 * 1. 读取输入的华氏温度F
 * 2. 按照公式计算摄氏温度C
 * 3. 注意运算顺序：先计算括号内的减法，再乘以5，最后除以9
 * 4. 按照指定格式输出结果
 */
int main() {
    int F;
    cin >> F;
    
    // 应用转换公式计算摄氏温度
    int C = 5 * (F - 32) / 9;
    
    // 按指定格式输出结果
    cout << "Celsius = " << C << endl;
    
    return 0;
}