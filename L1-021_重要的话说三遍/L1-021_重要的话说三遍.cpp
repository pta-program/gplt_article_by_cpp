#include <iostream>
using namespace std;

/**
 * L1-021 - 重要的话说三遍
 * 
 * 实现原理：
 * 这是一个简单的输出程序，不需要任何输入处理。
 * 连续输出三遍指定字符串，每遍占一行。
 * 
 * 解题思路：
 * 1. 使用循环输出三遍字符串
 * 2. 或者直接输出三次
 */
int main() {
    // 连续输出三遍重要的话
    for (int i = 0; i < 3; i++) {
        cout << "I'm gonna WIN!" << endl;
    }
    
    return 0;
}