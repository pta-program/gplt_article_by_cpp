#include <iostream>
using namespace std;

/**
 * L1-024 - 后天
 * 
 * 实现原理：
 * 后天就是今天加2天。由于星期是循环的（1-7），需要处理边界情况。
 * 如果今天是6（星期六），后天是1（星期一）
 * 如果今天是7（星期日），后天是2（星期二）
 * 
 * 解题思路：
 * 1. 读取今天是星期几（D）
 * 2. 计算后天：(D + 2 - 1) % 7 + 1
 *    使用公式 (D + 2 - 1) % 7 + 1 可以正确处理边界情况
 */
int main() {
    int D;
    cin >> D;
    
    // 计算后天是星期几
    // 使用模运算处理循环，(D + 2 - 1) % 7 + 1 确保结果在1-7范围内
    int result = (D + 2 - 1) % 7 + 1;
    
    cout << result << endl;
    
    return 0;
}