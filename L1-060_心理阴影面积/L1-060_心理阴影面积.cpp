#include <iostream>
using namespace std;

/**
 * L1-060 - 心理阴影面积
 * 
 * 实现原理：
 * 根据题目描述，心理阴影面积是红蓝线围出的面积。
 * 这是一个简单的几何问题：
 * - 蓝色直线是从(0,0)到(100,100)的对角线
 * - 红色折线是从(0,0)到(x,y)再到(100,100)
 * 
 * 阴影面积 = 三角形面积 = (100 - x) * (100 - y) / 2
 * 
 * 解题思路：
 * 1. 读取拐点坐标(x,y)
 * 2. 计算阴影面积
 * 3. 输出结果
 */
int main() {
    int x, y;
    cin >> x >> y;
    
    // 计算心理阴影面积
    // 阴影是一个三角形，底为(100-x)，高为(100-y)
    int area = (100 - x) * (100 - y) / 2;
    
    cout << area << endl;
    
    return 0;
}