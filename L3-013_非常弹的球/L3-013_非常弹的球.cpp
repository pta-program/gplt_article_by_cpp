/*
 * L3-013 非常弹的球
 *
 * 题目描述：
 *   一个非常有弹性的球从高处落下，落地后会反弹。每次反弹后，球的动能会按固定比例衰减。
 *   假设每次都以 45 度角抛出，求球最终停止前总共经过的水平距离。
 *   输入格式：第一行给出两个实数 w 和 p，分别表示球的重量（克）和动能保留百分比。
 *   输出格式：输出球总共经过的水平距离，保留三位小数。
 *
 * 实现原理：
 *   物理问题转化为等比级数求和问题。
 *   1. 根据物理公式，第一次抛出的最远距离为：first = 2000.0 / (m * 9.8)，其中 m = w / 1000.0 是质量（千克）。
 *   2. 每次落地后动能按 p% 衰减，因此每次反弹的射程也按 sqrt(p%) 衰减（射程与速度成正比，速度平方与动能成正比）。
 *   3. 所有射程构成等比级数，首项为 first，公比为 p/100。
 *   4. 等比级数求和：answer = first / (1 - p/100)。
 *
 * 时间复杂度：O(1)，直接使用公式计算
 */
int main(void) {
    double w,p,m,first,answer; scanf("%lf%lf",&w,&p); m=w/100.0;
    first=2000.0/(m*9.8); answer=first/(p/100.0);
    printf("%.3f\n",answer);return 0;
}
